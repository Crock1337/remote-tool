import os, base64
from cryptography.hazmat.primitives.ciphers.aead import AESGCM

_MASTER = bytes([
    0x3a,0x7f,0x11,0xc4,0x9e,0x52,0x88,0x1d,0x6b,0x03,0xf7,0x2c,0x45,0xa1,0xde,0x70,
    0x19,0xb8,0x63,0x0f,0x92,0x4d,0xe6,0x35,0x7a,0xc8,0x21,0x5e,0xaf,0x84,0xd3,0x0b,
])

def _key() -> bytes:
    return _MASTER

def enc(plain: str) -> str:
    nonce = os.urandom(12)
    ct = AESGCM(_key()).encrypt(nonce, plain.encode(), None)
    return base64.b64encode(nonce + ct).decode()

def dec(token: str) -> str:
    raw = base64.b64decode(token)
    nonce, ct = raw[:12], raw[12:]
    return AESGCM(_key()).decrypt(nonce, ct, None).decode()
